const assert=require('node:assert/strict')
const {chromium}=require('playwright')
const {openStudio}=require('./studio-nav.cjs')
const url=process.argv[2] || 'http://127.0.0.1:8736/'

async function check(page,mobile) {
  await page.goto(url)
  await page.waitForFunction(()=>window.hydraSynth && window.fosfenoStack)
  const id=k=>page.locator('#'+k)
  const rows=()=>page.evaluate(()=>fosfenoStack.snapshot().rows.filter(r=>r.id))
  const count=n=>page.waitForFunction(n=>fosfenoStack.snapshot().rows.filter(r=>r.id).length===n,n)
  const menu=id('stackContextMenu')
  await openStudio(page,'sectors')
  const ref=await page.evaluate(()=>fosfenoStack.geometry.create('Rectángulo',[[.1,.1],[.4,.1],[.4,.4],[.1,.4]],'#e82b41'))
  const sector=page.locator('.layer-overview-row[data-sector-id="'+ref.sectorId+'"] .layer-select')
  if (mobile) await id('stackContext').tap()
  else await sector.click({button:'right'})
  assert.equal(await menu.getAttribute('role'),'menu')
  await menu.locator('[data-action=duplicate]').click()
  await count(2)
  await id('stackContext').focus()
  await page.keyboard.press('Control+z')
  await count(1)
  await page.keyboard.press('Control+y')
  await count(2)
  await sector.focus()
  await page.keyboard.press('Shift+F10')
  await menu.getByRole('menuitem',{name:'Centrar en el lienzo'}).click()
  const find=async()=>(await rows()).find(r=>r.id===ref.sectorId).points[0][0]
  const x=await find()
  assert.ok(Math.abs(x-.35)<.00001)
  await sector.focus()
  await page.keyboard.press('Shift+ArrowRight')
  assert.ok(await find()>x)
  await sector.focus()
  await page.keyboard.press('Control+c')
  await page.keyboard.press('Control+v')
  await count(3)
  await id('stackContext').focus()
  await page.keyboard.press('Control+d')
  await count(4)
  await page.keyboard.press('Delete')
  await count(3)
  await page.evaluate(ref=>fosfenoStack.command('effects',ref),ref)
  await id('sectorFx').getByRole('button',{name:'Invertir',exact:true}).click()
  const effectRef={...ref,kind:'effect',index:0}
  await page.evaluate(async r=>{await fosfenoStack.command('amount',r,.35);await fosfenoStack.command('select',r)},effectRef)
  if (mobile) await id('stackContext').tap()
  else await page.locator('#sector-tree-'+ref.sectorId+' .layer-tree-effect-name').first().click({button:'right'})
  await menu.locator('[data-action=duplicate]').click()
  const effects=async()=>(await rows()).find(r=>r.id===ref.sectorId).entries[0].effects
  assert.deepEqual((await effects()).map(f=>f.value),[.35,.35])
  await openStudio(page,'code')
  await page.evaluate(()=>{cm.focus();cm.setCursor(0,0)})
  await page.keyboard.press('v')
  assert.equal(await page.evaluate(()=>cm.getValue().startsWith('v')),true)
  await page.keyboard.press('Control+z')
  assert.equal((await rows()).length,3)

  await id('openMapping').click()
  const map=page.frameLocator('#mappingFrame'), inside=k=>map.locator('#'+k)
  const native=map.locator('#mapLayers .map-layer-name')
  await inside('mapNewInk').click()
  const surface=inside('mapSurface')
  const box=await surface.boundingBox(),x1=box.x+box.width*.15,y1=box.y+box.height*.35
  await page.mouse.move(x1,y1)
  await page.mouse.down()
  await page.mouse.move(x1+box.width*.2,y1+box.height*.1,{steps:6})
  await page.mouse.up()
  await native.first().click()
  const list=inside('mapContextMenu')
  if (mobile) await inside('mapContext').tap()
  else await page.mouse.click(x1+box.width*.10,y1+box.height*.05,{button:'right'})
  await list.locator('[data-action=duplicate]').click()
  assert.equal(await native.count(),2)
  await native.first().focus()
  await page.keyboard.press('Control+d')
  assert.equal(await native.count(),3)
  await surface.focus()
  await page.keyboard.press('Delete')
  assert.equal(await native.count(),2)
  await page.keyboard.press('Control+z')
  assert.equal(await native.count(),3)
  await native.first().focus()
  await page.keyboard.press('Shift+F10')
  await list.getByRole('menuitem',{name:'Editar',exact:true}).click()
  await page.keyboard.press('b')
  await page.keyboard.press('Delete')
  assert.equal(await native.count(),3)
  assert.equal(await inside('mapLayerName').inputValue(),'b')
  await surface.focus()
  for (const [key,tool] of [['b','brush'],['l','line'],['v','select']]) {
    await page.keyboard.press(key)
    assert.equal(await map.locator('[data-tool="'+tool+'"]').getAttribute('aria-pressed'),'true')
  }
  await inside('mapContext').click()
  const rect=await list.boundingBox(), frame=await id('mappingFrame').boundingBox()
  assert.ok(rect.x>=0 && rect.y>=0 && rect.x+rect.width<=frame.x+frame.width+1 && rect.y+rect.height<=frame.y+frame.height+1)
  await page.keyboard.press('Escape')
  assert.equal(await list.isHidden(),true)
  await inside('mapContext').click()
  await list.locator('[data-action=shortcuts]').click()
  await map.getByRole('dialog',{name:'Atajos de edición'}).waitFor()
  await page.keyboard.press('Control+d')
  assert.equal(await native.count(),3)
  await page.keyboard.press('Escape')
  const mappedEffect=map.locator('[data-stack-kind=effect][data-sector-id="'+ref.sectorId+'"][data-index="0"] .map-layer-name')
  if (mobile) {
    await mappedEffect.click()
    await inside('mapContext').tap()
  } else await mappedEffect.click({button:'right'})
  await list.locator('[data-action=toggle]').click()
  assert.deepEqual((await effects()).map(f=>f.enabled),[false,true])
}
;(async()=>{
  const browser=await chromium.launch({channel:'chromium',args:['--enable-unsafe-swiftshader']})
  try {
    for (const mobile of [false,true]) {
      const page=await browser.newPage({viewport:mobile?{width:375,height:760}:{width:1440,height:900},isMobile:mobile,hasTouch:mobile,serviceWorkers:'block'})
      page.setDefaultTimeout(8000)
      const errors=[]
      page.on('pageerror',e=>errors.push(e.message))
      await check(page,mobile)
      assert.deepEqual(errors,[])
      console.log((mobile?'375 px, puntero táctil':'1440 px, mouse')+' · Menús, foco, duplicar, copiar, pegar, centrar, mover, deshacer y herramientas.')
      await page.close()
    }
  } finally { await browser.close() }
})().catch(e=>{console.error(e);process.exitCode=1})
