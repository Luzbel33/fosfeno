const assert=require('node:assert/strict')
const {chromium}=require('playwright')
const {openStudio}=require('./studio-nav.cjs')
const url=process.argv[2] || 'http://127.0.0.1:8736/'

async function inspect(page,mobile) {
  const id=name=>page.locator('#'+name)
  const menu=id('stackContextMenu')
  const choose=(action,root=menu)=>root.locator('[data-action="'+action+'"]').click()
  const pointed=async locator=>{await locator.click({button:'right'});await menu.waitFor()}
  const focused=locator=>locator.evaluate(node=>node===node.ownerDocument.activeElement)
  const cmd=(action,ref)=>page.evaluate(([a,r])=>fosfenoStack.command(a,r),[action,ref])
  await page.goto(url)
  await page.waitForFunction(()=>window.hydraSynth && window.fosfenoStack)
  await openStudio(page,'sectors')
  const [a,b]=await page.evaluate(()=>[.1,.6].map(x=>fosfenoStack.geometry.create('Rectángulo',[[x,.2],[x+.25,.2],[x+.25,.7],[x,.7]],'#cd89ff')))
  const row=ref=>page.locator('.layer-overview-row[data-sector-id="'+ref.sectorId+'"] .layer-select')
  await cmd('select',b)
  await pointed(row(a))
  await choose('inspect')
  assert.ok(await focused(id('sectorFillToggle')))
  await cmd('effects',a)
  await id('sectorFx').getByRole('button',{name:'Invertir',exact:true}).click()
  await cmd('select',a)
  const inline=page.locator('#sectorControls .mixer-effect')
  await pointed(inline.locator('strong').first())
  assert.equal(await menu.getAttribute('aria-label'),'Acciones de Invertir')
  await choose('inspect')
  assert.ok(await focused(inline.locator('input').first()))
  await inline.locator('input').first().fill('0.37')
  assert.equal(await page.evaluate(id=>fosfenoStack.snapshot().rows.find(row=>row.id===id).entries[0].effects[0].value,a.sectorId),.37)
  await cmd('media',a)
  await page.locator('[data-sector-src=s0]').click()
  await id('sectorPaint').click()
  await id('sectorCodeToggle').click()
  await id('sectorCode').fill('return base().rotate(0.37)')
  await id('sectorApplyCode').click()
  await cmd('addLayer',a)
  const layerRef=await page.evaluate(()=>fosfenoStack.snapshot().selection)
  assert.ok(layerRef.layerId)
  await cmd('select',b)
  const layer=page.locator('#sector-tree-'+a.sectorId+' .layer-tree-name').last()
  await pointed(layer)
  await choose('inspect')
  assert.ok(await focused(id('sectorOpacity')))
  await id('groupSectorLayers').click()
  await page.getByRole('button',{name:'Marcar Base',exact:true}).click()
  await page.getByRole('button',{name:'Marcar Capa 2',exact:true}).click()
  await id('createSectorGroup').click()
  const groupRef=await page.evaluate(()=>fosfenoStack.snapshot().selection)
  assert.equal(groupRef.kind,'group')
  await cmd('select',b)
  const group=page.locator('#sector-tree-'+a.sectorId+' .layer-tree-name').filter({hasText:'Grupo'})
  await pointed(group)
  await choose('inspect')
  assert.ok(await focused(id('sectorOpacity')))

  const component=kind=>page.locator('#sector-tree-'+a.sectorId+' [data-stack-item]').filter({hasText:kind})
  await cmd('select',b)
  await pointed(component('Señal').or(component('s0')).first())
  await choose('inspect')
  assert.ok(await focused(page.locator('[data-sector-src=s0]')))
  await cmd('select',b)
  await pointed(component('Pinceladas').first())
  await choose('inspect')
  assert.ok(await focused(id('sectorBrushSize')))
  const viewCode=async()=>{
    await openStudio(page,'sectors')
    await cmd('select',b)
    await pointed(component('Código Hydra').first())
    await choose('code')
  }
  const scopedCode=id('contextCodeBox').locator('.CodeMirror')
  const currentCode=()=>scopedCode.evaluate(box=>box.CodeMirror.getValue())
  // Right-click another region while deforming a different one.
  await openStudio(page,'sectors')
  await cmd('select',b)
  if (await id('sectorDeform').getAttribute('aria-pressed')!=='true') await id('sectorDeform').click()
  const box=await id('sectorGuide').boundingBox()
  await page.mouse.click(box.x+box.width*.2,box.y+box.height*.4,{button:'right'})
  assert.equal(await menu.getAttribute('aria-label'),'Acciones de Rectángulo '+a.sectorId)
  await page.keyboard.press('Escape')

  await id('openMapping').click()
  const map=page.frameLocator('#mappingFrame')
  const mapMenu=map.locator('#mapContextMenu')
  const mapped=(ref,kind)=>map.locator('[data-sector-id="'+ref.sectorId+'"][data-stack-kind="'+kind+'"] .map-layer-name').first()
  await mapped(b,'sector').click()
  const fx=mapped(a,'effect')
  await fx.focus()
  await page.keyboard.press('Shift+F10')
  await mapMenu.waitFor()
  await mapMenu.evaluate(el=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
  assert.ok(await focused(mapMenu.locator('[data-action=inspect]')))
  await page.keyboard.press('Escape')
  assert.ok(await focused(fx))
  if (mobile) {
    await fx.tap()
    await map.locator('#mapContext').tap()
  } else await fx.click({button:'right'})
  await choose('inspect',mapMenu)
  assert.ok(await id('mappingFrame').isHidden())
  assert.ok(await focused(inline.locator('input').first()))
  assert.equal(await inline.locator('input').first().inputValue(),'0.37')
  await id('mappingSurface').click()
  await mapped(b,'sector').click()
  const code=mapped(a,'code')
  await code.click({button:'right'})
  await choose('inspect',mapMenu)
  await id('visualParameters').waitFor()
  assert.ok(await id('mappingFrame').isVisible())
  await id('cancelVisualParams').click()
  await code.click({button:'right'})
  await choose('code',mapMenu)
  await scopedCode.waitFor()
  assert.equal(await currentCode(),'return base().rotate(0.37)')
  await id('exitMapping').click()
  await viewCode()
  assert.equal(await currentCode(),'return base().rotate(0.37)')
  console.log((mobile?'375 px':'1440 px')+' · Sector, capa, grupo, fuente, pinceladas, código y efecto apuntan al inspector correcto. Foco y menú sobreviven al cambio de fila.')
}
;(async()=>{
  const browser=await chromium.launch({channel:'chromium',args:['--enable-unsafe-swiftshader']})
  try {
    for (const mobile of [false,true]) {
      const page=await browser.newPage({viewport:{width:mobile?375:1440,height:mobile?780:900},isMobile:mobile,hasTouch:mobile,serviceWorkers:'block'})
      page.setDefaultTimeout(8000)
      const errors=[]
      page.on('pageerror',error=>errors.push(error.message))
      await inspect(page,mobile)
      assert.deepEqual(errors,[])
      await page.close()
    }
  } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
