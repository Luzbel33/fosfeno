const assert = require('node:assert/strict')
const path = require('node:path')
const { chromium } = require('playwright')

async function main() {
  const b = await chromium.launch({channel:'chromium',args:['--use-angle=d3d11','--enable-unsafe-swiftshader','--use-fake-device-for-media-stream']})
  try {
    const page = await b.newPage({viewport:{width:1200,height:800}})
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    const id = n => page.locator('#'+n)
    const tab = n => page.locator('[data-view="'+n+'"]').click()
    const waitPixel = async (x,y,rgb) => page.waitForFunction(({x,y,rgb}) => {
      hydraSynth.tick(32)
      const canvas = hydraSynth.canvas
      const p = hydraSynth.regl.read({x:Math.floor(x*canvas.width),y:Math.floor((1-y)*canvas.height),width:1,height:1})
      return rgb.every((v,i) => Math.abs(p[i]-v) <= 2)
    },{x,y,rgb}, {timeout:8000})
    async function draw(shape, points) {
      await id('newSector').click()
      await id('sectorShapes').getByRole('button',{name:shape,exact:true}).click()
      const r = await id('sectorGuide').boundingBox()
      for (const [i,[x,y]] of points.entries()) {
        await page.mouse.move(r.x+x*r.width,r.y+y*r.height,{steps:i?5:1})
        if (i === 0) await page.mouse.down()
      }
      await page.mouse.up()
    }
    const red = [255,0,0], cyan = [0,255,255], blue = [0,0,255]
    await page.goto(process.argv[2] || 'http://127.0.0.1:8736/')
    await page.waitForFunction(() => window.cm?.getValue().includes('MULTIVERSE') && window.hydraSynth)
    assert.equal(await page.locator('#ops small').count(),0)
    await page.locator('[data-help="efectos"]').click()
    assert.equal(await page.locator('#helpDialog[open] dt').count(),12)
    assert.ok(await id('helpContent').getByText('Refleja de izquierda a derecha').isVisible())
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('#helpDialog[open]').count(),0)
    assert.equal(await id('outputChoices').isVisible(),false)
    await id('chooseOutput').click()
    await page.locator('[data-output="2"]').click()
    await page.waitForFunction(()=>hydraSynth.output===o2 && document.querySelector('#chooseOutput').textContent.includes('Salida 3'))
    await id('chooseOutput').click()
    await page.locator('[data-output="0"]').click()
    await page.locator('[data-help="autopiloto"]').click()
    assert.match(await id('helpContent').innerText(),/intervalo/)
    await id('closeHelp').click()
    assert.equal(await id('liveEdit').getAttribute('aria-pressed'),'true')
    await page.evaluate(() => cm.setValue('solid(1,0,0).out(o0)'))
    await waitPixel(.4,.4,red)
    await id('ops').getByRole('button',{name:/Espejo X/}).click()
    await id('removeMode').click()
    await id('activeEffects').getByRole('button',{name:/Quitar Espejo X/}).click()
    assert.equal(await page.evaluate(()=>cm.getValue()),'solid(1,0,0).out(o0)')
    await tab('library')
    await id('sketchList').getByRole('button',{name:'Mezclar Nácar en fuga',exact:true}).click()
    await page.waitForFunction(() => cm.getValue().includes('capaBiblioteca') && document.querySelector('#codeStatus').textContent.includes('Sketch ejecutado'))
    await id('mixInfo').click()
    await page.waitForFunction(() => document.querySelector('#mixDetail').textContent.includes('Biblioteca · Nácar en fuga'))
    await id('mixInfo').click()
    await tab('code')
    await id('activeEffects').getByRole('button',{name:/Quitar Nácar en fuga/}).click()
    await waitPixel(.4,.4,red)
    assert.equal(await page.evaluate(()=>cm.getValue()),'solid(1,0,0).out(o0)')

    await tab('sectors')
    await draw('Rectángulo',[[.15,.15],[.85,.85]])
    const invert = async () => {
      await id('addSectorEffect').click()
      await id('sectorFx').getByRole('button',{name:'Invertir'}).click()
    }
    await invert()
    await waitPixel(.35,.35,cyan)
    await waitPixel(.05,.05,red)
    await draw('Círculo',[[.37,.37],[.64,.64]])
    const image = await page.evaluate(() => {
      const c = document.createElement('canvas'); c.width = c.height = 64
      const ctx = c.getContext('2d'); ctx.fillStyle='#00f'; ctx.fillRect(0,0,64,64)
      return c.toDataURL().split(',')[1]
    })
    const picker = page.waitForEvent('filechooser')
    await id('sectorFileButton').click()
    await (await picker).setFiles({name:'azul.png',mimeType:'image/png',buffer:Buffer.from(image,'base64')})
    await waitPixel(.49,.49,blue)
    await waitPixel(.20,.20,cyan)
    await id('sectorPaint').click()
    await page.waitForFunction(() => {
      hydraSynth.tick(40)
      const {width,height} = hydraSynth.canvas
      const rgba = hydraSynth.regl.read({x:Math.floor(.45*width),y:Math.floor(.5*height),width:12,height:12})
      return rgba.some((v,i)=>i%4===2 && v>100 && rgba[i-2]<10)
    })
    await id('sectorPaint').click()
    await id('saveSectors').click()
    await page.waitForFunction(()=>document.querySelector('#sectorStatus').textContent.includes('guardados'))
    await id('sectorDelete').click()
    await waitPixel(.49,.49,cyan)
    await id('loadSectors').click()
    await waitPixel(.49,.49,blue)
    await id('sectorVisible').click()
    await waitPixel(.49,.49,cyan)
    await id('sectorVisible').click()
    const video = page.waitForEvent('filechooser')
    await id('sectorFileButton').click()
    await (await video).setFiles(path.join(__dirname,'../media/fosfeno-demo.mp4'))
    await page.waitForFunction(()=>document.querySelector('#sectorFileButton').textContent.includes('mp4'))
    await page.waitForFunction(()=> {
      hydraSynth.tick(32)
      const {width,height} = hydraSynth.canvas
      const p = hydraSynth.regl.read({x:Math.floor(width*.47),y:Math.floor(height*.5),width:8,height:8})
      return p.some((v,i)=>i%4===2 && v<225)
    })
    await waitPixel(.20,.20,cyan)
    await id('sectorDelete').click()
    for (const shape of ['Cuadrado','Rombo','Triángulo','Libre']) {
      await draw(shape,[[.3,.25],[.65,.6],[.4,.7], [.28,.55]])
      assert.ok((await id('sectorTitle').textContent()).includes(shape))
      await id('sectorDelete').click()
    }
    await tab('code')
    await id('liveEdit').click()
    await tab('sectors')
    await id('sectorDelete').click()
    await waitPixel(.4,.4,cyan)
    await id('applySectors').click()
    await waitPixel(.4,.4,red)
    await draw('Rectángulo',[[.2,.2],[.7,.7]])
    await page.context().grantPermissions(['camera'])
    await page.locator('[data-sector-src="s0"]').click()
    await id('sectorCamera').click()
    await page.waitForFunction(()=>document.querySelector('#sectorStatus').textContent.includes('Webcam conectada'))
    assert.equal(await page.evaluate(()=>cm.getValue()),'solid(1,0,0).out(o0)')
    await id('applySectors').click()
    await waitPixel(.07,.07,red)
    await page.waitForFunction(()=>{
      hydraSynth.tick(32)
      const {width,height} = hydraSynth.canvas
      const p=hydraSynth.regl.read({x:Math.floor(.45*width),y:Math.floor(.55*height),width:1,height:1})
      return p[0]<245 || p[1]>10 || p[2]>10
    })
    await id('sectorDelete').click()
    await id('applySectors').click()
    await tab('signal')
    await id('clearVisual').click()
    await tab('code')
    await page.evaluate(()=>cm.setValue('solid(0,0,1).out()'))
    await page.waitForTimeout(350)
    await waitPixel(.5,.5,red)
    await id('run').click()
    await waitPixel(.5,.5,blue)
    await id('liveEdit').click()
    await tab('sectors')
    await draw('Rectángulo',[[.25,.25],[.75,.75]])
    await invert()
    const popup = page.waitForEvent('popup')
    await id('project').click()
    const output = await popup
    await output.waitForFunction(()=>document.querySelector('video')?.readyState>=2)
    assert.deepEqual(await output.evaluate(()=>[...document.body.children].map(e=>e.tagName)),['VIDEO'])
    assert.equal(await output.locator('video').evaluate(v=>v.controls),false)
    await output.waitForFunction(()=>{
      const c=document.createElement('canvas'); c.width=c.height=20
      const g=c.getContext('2d'); g.drawImage(document.querySelector('video'),0,0,20,20)
      const center=g.getImageData(10,10,1,1).data, outside=g.getImageData(1,1,1,1).data
      return center[0]>220 && center[1]>220 && center[2]<25 && outside[2]>220 && outside[0]<25
    })
    await output.close()
    await tab('signal')
    await page.locator('[data-tab="out"]').click()
    await id('fullPanel').click()
    assert.equal(await page.evaluate(()=>document.fullscreenElement?.id),'visual')
    await page.evaluate(()=>document.exitFullscreen())
    await tab('code')
    while (!(await id('interval').textContent()).trim().startsWith('15 s')) await id('interval').click()
    await id('automate').click()
    await page.waitForFunction(()=>document.querySelector('#scoreName').value.startsWith('Semilla '),null,{timeout:30000})
    await page.evaluate(()=>cm.replaceRange('// edición\n',{line:0,ch:0}))
    assert.equal(await id('automate').getAttribute('aria-pressed'),'false')
    assert.deepEqual(errors,[])
    console.log('PASS: direct/manual editing, reversible operators and library layers, six sector shapes, isolated pixels, photo/video, brush, save/restore, stacked sectors, clean projector pixels and canvas fullscreen.')
  } finally { await b.close() }
}
main().catch(e=>{console.error(e);process.exitCode=1})
