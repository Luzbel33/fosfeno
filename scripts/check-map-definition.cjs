const assert=require('node:assert/strict')
const path=require('node:path')
const {chromium}=require('playwright')
async function main() {
  const url=new URL(process.argv[2] || 'http://127.0.0.1:8736/')
  url.searchParams.set('mode','mapeo')
  const browser=await chromium.launch({channel:'chromium',args:['--use-angle=d3d11','--enable-unsafe-swiftshader']})
  try {
    const p=await browser.newPage({viewport:{width:1440,height:900},serviceWorkers:'block'})
    const errors=[];p.on('pageerror',e=>errors.push(e.message))
    await p.goto(url.href)
    const m=p.frameLocator('#mappingFrame'),id=n=>m.locator('#'+n)
    await id('mapMain').waitFor()
    const draw=async(a,b)=>{
      const box=await id('mapPreview').boundingBox()
      await p.mouse.move(box.x+box.width*a[0],box.y+box.height*a[1]);await p.mouse.down()
      await p.mouse.move(box.x+box.width*b[0],box.y+box.height*b[1],{steps:32});await p.mouse.up()
    }
    const model=async()=>{const cm=p.locator('#contextCodeBox .CodeMirror');await cm.waitFor()
      return cm.evaluate(el=>({json:JSON.parse(el.CodeMirror.getValue()),ro:el.CodeMirror.getOption('readOnly')}))}
    const back=()=>p.locator('#codeReturnMap').click()
    await m.locator('[data-tool=brush]').click()
    await draw([.12,.23],[.31,.33])
    await id('mapLayers').getByRole('button',{name:'Trazos 1',exact:true}).click()
    await p.locator('#studioNav [data-view=code]').click()
    const ink=await model();assert.equal(ink.ro,true);assert.equal(ink.json.kind,'ink')
    assert.ok(ink.json.strokes[0].points.length>=2 && ink.json.strokes[0].points.length<=24)
    await back()
    await id('mapLayers').getByRole('button',{name:'Trazos 1',exact:true}).click({button:'right'})
    await id('mapContextMenu').getByRole('menuitem',{name:'Ver definición',exact:true}).click()
    assert.deepEqual((await model()).json,ink.json);await back()
    await id('mapShape').click();await m.locator('[data-map-shape="Óvalo"]').click()
    await draw([.10,.11],[.5,.62])
    await p.waitForFunction(()=>fosfenoStack.snapshot().rows.some(r=>r.id))
    const sector=await p.evaluate(()=>fosfenoStack.snapshot().rows.find(r=>r.id).name)
    await id('mapShape').click();await m.locator('[data-map-solid=cube]').click()
    await id('mapSolidFaces').getByRole('button',{name:'Frente',exact:true}).click()
    await id('mapFaceHydra').click()
    await id('mapFaceSources').getByRole('button',{name:sector,exact:true}).click()
    await id('mapObjectCode').click()
    const solid=await model();assert.equal(solid.json.solid.shape,'cube');assert.equal(solid.json.solid.faces.length,6)
    assert.equal(solid.json.selectedFace,'Frente');assert.ok(solid.json.solid.faces.some(f=>f.type==='hydra'))
    await back();await id('mapCodeOrigin').click()
    await p.locator('#codeReturnMap').waitFor()
    assert.ok((await p.locator('#codeDestination').textContent()).includes(sector),await p.locator('#codeDestination').textContent())
    await back()
    await id('mapMediaFile').setInputFiles(path.join(__dirname,'../media/modelos/nudo-de-cobre.glb'))
    await m.locator('#mapSurface[data-cursor=place]').waitFor()
    await draw([.37,.1],[.7,.7])
    await id('mapObjectCode').click()
    const file=(await model()).json
    assert.equal(file.file.name,'nudo-de-cobre.glb');assert.ok(file.file.model.meshes.total>=3);assert.ok(file.file.model.materials.total>=3)
    assert.ok(JSON.stringify(file).length<15000)
    await back()
    await id('mapAddHydra').click()
    await draw([.15,.42],[.4,.8])
    await id('mapObjectCode').click()
    assert.equal((await model()).json.kind,'hydra'); await back()
    await id('mapCodeOrigin').click()
    await p.locator('#codeReturnMap').waitFor()
    assert.deepEqual(errors,[])
    console.log('Mapeo → Código: definición de tinta desde cabecera y menú, cara de cubo y origen Hydra, modelo GLB con mallas/materiales, recorte y regreso al mapa.')
  } finally {await browser.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
