const { openStudio } = require('./studio-nav.cjs')
const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const url = new URL(process.argv[2] || 'http://127.0.0.1:8736/')
url.searchParams.set('sketch_id','eerie_ear_0')

async function main() {
  const browser = await chromium.launch({channel:'chromium',args:['--use-angle=d3d11','--enable-unsafe-swiftshader']})
  const failures=[]
  async function studio() {
    const p=await browser.newPage({viewport:{width:1100,height:768}})
    p.on('pageerror',e=>failures.push(e.message))
    await p.goto(url.href)
    await p.waitForFunction(()=>window.hydraSynth && window.cm?.getValue().includes('MULTIVERSE'))
    return p
  }
  const tab=openStudio
  const setCode=(p,text)=>p.evaluate(text=>cm.setValue(text),text)
  const projects=async p=>{
    await tab(p,'library')
    if (!await p.locator('#projectSave').isVisible())
      await p.locator('#projectLibrary > summary').click()
  }
  async function pixels(p,x,y,color) {
    await p.waitForFunction(({x,y,color})=>{
      hydraSynth.tick(32)
      const c=hydraSynth.canvas, a=hydraSynth.regl.read({x:Math.floor(x*c.width),y:Math.floor((1-y)*c.height),width:1,height:1})
      return color.every((n,i)=>Math.abs(a[i]-n)<4)
    },{x,y,color},{timeout:7000})
  }
  async function drag(p,a,b) {
    const r=await p.locator('#sectorGuide').boundingBox()
    await p.mouse.move(r.x+a[0]*r.width,r.y+a[1]*r.height)
    await p.mouse.down()
    await p.mouse.move(r.x+b[0]*r.width,r.y+b[1]*r.height,{steps:6})
    await p.mouse.up()
  }
  async function download(row) {
    const clicked=row.page().waitForEvent('download')
    await row.getByRole('button',{name:'Descargar'}).click()
    const d=await clicked
    return {name:d.suggestedFilename(),mimeType:'application/octet-stream',buffer:await require('fs').promises.readFile(await d.path())}
  }
  try {
    const p=await studio(), initial=await p.evaluate(()=>cm.getValue())
    await tab(p,'code')
    await p.locator('[data-help=codigo]').click()
    await p.locator('#lineGuide').click()
    assert.ok(await p.locator('.line-note').count()>0)
    assert.equal(await p.evaluate(()=>cm.getValue()),initial)
    await p.locator('[data-help=codigo]').click();await p.locator('#lineGuide').click()
    await tab(p,'sectors')
    await p.locator('#addSectorEffect').click()
    await p.locator('#effectSearch').fill('rotate')
    await p.locator('#hydraChoices').getByRole('button',{name:/^rotate/}).click()
    assert.match(await p.locator('#sectorControls').innerText(),/rotate/)
    await p.getByRole('button',{name:'Quitar rotate de toda la visual'}).click()
    await tab(p,'code')
    await setCode(p,'// Prueba de autoría\nsolid(1,0,0).rotate(-0.75).out(o0)')
    await p.locator('#scoreName').fill('Ensayo portátil')
    await p.locator('#adjustMode').click()
    await p.locator('#operatorInspector summary').click()
    await p.locator('#operatorInspector').getByRole('button',{name:/^rotate ·/}).click()
    const field=p.getByRole('textbox',{name:'rotate · angle',exact:true})
    assert.equal(await field.inputValue(),'-0.75')
    await field.fill('-0.45');await field.press('Enter')
    await p.locator('#operatorInspector').getByText('Guardar este operador').click()
    await p.waitForFunction(()=>document.querySelector('#toast').textContent.includes('Operador guardado'))
    const source=await p.evaluate(()=>cm.getValue())
    assert.ok(source.includes('rotate(-0.45)'))
    await p.evaluate(()=>cm.setCursor(cm.posFromIndex(cm.getValue().indexOf('0.45')+2)))
    assert.equal(await p.locator('#tune').inputValue(),'-0.45')
    await tab(p,'sectors')
    await p.locator('#newSector').click()
    await p.locator('#sectorShapes').getByText('Rectángulo',{exact:true}).click()
    await drag(p,[.15,.15],[.85,.85])
    const image=await p.evaluate(()=>{
      const c=document.createElement('canvas');c.width=c.height=32
      const g=c.getContext('2d');g.fillStyle='blue';g.fillRect(0,0,32,32);return c.toDataURL().split(',')[1]
    })
    const chooser=p.waitForEvent('filechooser')
    await p.locator('#sectorMediaToggle').click()
    await p.locator('#sectorFileButton').click()
    await (await chooser).setFiles({name:'azul.png',mimeType:'image/png',buffer:Buffer.from(image,'base64')})
    await pixels(p,.2,.20,[0,0,255])
    await p.locator('#sectorDeform').click()
    await drag(p,[.15,.15],[.53,.30])
    await pixels(p,.20,.20,[255,0,0])
    await p.locator('#addSectorEffect').click()
    await p.locator('#sectorFx').getByText('Invertir',{exact:true}).click()
    await p.locator('#sectorControls input').fill('0.25')
    await p.locator('#sectorControls input').dispatchEvent('change')
    await pixels(p,.60,.6,[64,64,191])
    await p.locator('#sectorOpacity').fill('80')
    await pixels(p,.60,.6,[102,51,153])
    await p.getByRole('button',{name:'Toda la visual',exact:true}).click()
    await tab(p,'signal')
    await p.locator('#autoMixInput').click()
    await p.locator('#visualFile').setInputFiles({name:'entrada.png',mimeType:'image/png',buffer:Buffer.from(image,'base64')})
    await p.waitForFunction(()=>document.querySelector('#visualName').textContent.includes('entrada.png'))
    await projects(p)
    await p.locator('#projectSave').click()
    const row=p.locator('#projectList details').filter({has:p.getByText('Ensayo portátil',{exact:true})})
    await row.locator('summary').click()
    const project=await download(row)
    const op=p.locator('#projectList details').filter({hasText:'rotate · Ensayo portátil'})
    await op.locator('summary').click()
    const operator=await download(op)
    const dest=await studio()
    await projects(dest)
    assert.equal(await dest.locator('#projectList details').count(),0)
    await dest.locator('#projectFile').setInputFiles(project)
    await dest.locator('#projectList summary').first().click()
    assert.equal(await dest.evaluate(()=>cm.getValue()),initial)
    await dest.locator('#projectList').getByRole('button',{name:'Activar'}).click()
    await pixels(dest,.60,.6,[102,51,153]);await pixels(dest,.20,.2,[255,0,0])
    assert.equal(await dest.evaluate(()=>cm.getValue()),source)
    await tab(dest,'sectors')
    assert.equal(await dest.locator('#sectorControls input').inputValue(),'0.25')
    assert.equal(await dest.locator('#sectorOpacity').inputValue(),'80')
    assert.match(await dest.locator('#sectorFileButton').innerText(),/azul.png/)
    await dest.getByRole('button',{name:'Toda la visual',exact:true}).click()
    await tab(dest,'signal')
    assert.match(await dest.locator('#visualName').innerText(),/entrada.png/)
    assert.equal(await dest.locator('#autoMixInput').getAttribute('aria-pressed'),'false')
    await tab(dest,'code');await setCode(dest,'solid(0,1,0).out()')
    await projects(dest)
    await dest.locator('#projectFile').setInputFiles(operator)
    await dest.locator('#projectList summary').getByText('rotate · Ensayo portátil',{exact:true}).click()
    await dest.locator('#projectList').getByRole('button',{name:'Insertar'}).click()
    await dest.waitForFunction(()=>cm.getValue().includes('.rotate(-0.45)'),null,{timeout:5000})
    assert.match(await dest.evaluate(()=>cm.getValue()),/\/\/ Prueba de autoría[\s\S]*solid\(0,1,0\)\.rotate\(-0.45\)/)
    await projects(dest)
    await dest.locator('#projectFile').setInputFiles({...project,buffer:project.buffer.subarray(0,project.buffer.length-3)})
    await dest.waitForFunction(()=>document.querySelector('#toast').textContent.includes('incompleto'))
    assert.equal(await dest.locator('#projectList details').count(),2)
    assert.deepEqual(failures,[])
    console.log('Portable composition and operator passed across empty browser profiles, including exact code, local image, mask deformation, parameters, credits and corrupt file recovery.')
  } finally { await browser.close() }
}
main().catch(e=>{console.error(e);process.exitCode=1})
