const { openStudio } = require('./studio-nav.cjs')
const assert=require('node:assert/strict')
const {chromium}=require('playwright')

async function main() {
  const browser=await chromium.launch({channel:'chromium',args:['--use-angle=d3d11','--enable-unsafe-swiftshader','--use-fake-device-for-media-stream']})
  try {
    const page=await browser.newPage({viewport:{width:1440,height:900}})
    const errors=[]
    page.on('pageerror',e=>errors.push(e.message))
    const id=name=>page.locator('#'+name)
    const tab=name=>openStudio(page,name)
    const score='setResolution(320,180)\nsolid(1,0,0).out(o0)\nsolid(0,1,0).out(o1)\nsolid(0,0,1).out(o2)\nsolid(1,1,1).out(o3)\nrender(o0)'
    await page.goto(process.argv[2] || 'http://127.0.0.1:8736/')
    await page.waitForFunction(()=>window.hydraSynth && window.cm?.getValue().startsWith('// Semilla '))
    const initial=await page.evaluate(()=>cm.getValue())
    await page.reload()
    await page.waitForFunction(previous=>window.cm?.getValue().startsWith('// Semilla ') && cm.getValue()!==previous,initial)
    await page.evaluate(code=>cm.setValue(code),score)
    await page.waitForFunction(()=>hydraSynth.canvas.width===320)
    const pixel=(x,y,color)=>page.waitForFunction(({x,y,color})=>{
      const {regl,canvas}=hydraSynth
      const p=regl.read({x:Math.floor(x*canvas.width),y:Math.floor((1-y)*canvas.height),width:1,height:1})
      return color.every((v,i)=>Math.abs(v-p[i])<4)
    },{x,y,color},{timeout:6000})
    const help=page.locator('[data-help=autopiloto]')
    const trigger=await help.boundingBox()
    await help.click()
    const dialog=await id('helpDialog').boundingBox()
    assert.ok(Math.abs(trigger.x-dialog.x)<20 && dialog.y+dialog.height<=trigger.y)
    assert.match(await id('helpContent').innerText(),/proyecta un sketch nuevo/)
    await page.keyboard.press('Escape')
    await id('addSectorEffect').click()
    const mirror=id('sectorFx').getByRole('button',{name:'Espejo X',exact:true})
    await mirror.click()
    assert.equal(await mirror.getAttribute('aria-pressed'),'true')
    await mirror.click()
    assert.equal(await mirror.getAttribute('aria-pressed'),'false')
    assert.equal(await page.evaluate(()=>cm.getValue()),score)
    await id('liveEdit').click()
    assert.equal(await id('applySectors').isVisible(),false)
    await page.evaluate(()=>cm.setValue('solid(0,1,0).out(o0)'))
    await tab('library')
    assert.ok(await id('applySectors').isVisible() && await id('applySectors').isEnabled())
    await pixel(.5,.5,[255,0,0])
    await id('applySectors').click()
    await pixel(.5,.5,[0,255,0])
    assert.equal(await id('applySectors').isVisible(),false)
    await id('liveEdit').click()
    await tab('code')
    const custom='solid(0,0,1).out(o1)\nsrc(o1).blend(src(o0),.2).out(o0)\nrender(o0)'
    await page.evaluate(code=>cm.setValue(code),custom)
    await id('scoreName').fill('Eco azul')
    await id('save').click()
    await page.evaluate(code=>cm.setValue(code),score)
    await pixel(.5,.5,[255,0,0])
    await tab('library')
    const mix=page.getByRole('button',{name:'Mezclar Eco azul',exact:true})
    await mix.click()
    assert.equal(await mix.getAttribute('aria-pressed'),'true')
    await pixel(.5,.5,[127,0,127])
    assert.equal(await page.evaluate(()=>cm.getValue()),score)
    const mixSlider=id('mine').getByRole('slider',{name:'Mezcla de Eco azul'})
    const chainSlider=id('sectorControls').getByRole('slider',{name:'Mezcla de Eco azul'})
    await mixSlider.press('ArrowRight')
    assert.equal(await chainSlider.inputValue(),'0.51')
    await id('liveEdit').click()
    await chainSlider.press('End')
    assert.equal(await mixSlider.inputValue(),'100')
    assert.ok(await id('applySectors').isEnabled())
    await pixel(.5,.5,[125,0,130])
    await id('applySectors').click()
    await pixel(.5,.5,[0,0,255])
    await id('liveEdit').click()
    await mix.click()
    await pixel(.5,.5,[255,0,0])
    await tab('sectors')
    await id('newSector').click()
    await id('sectorShapes').getByText('Rectángulo',{exact:true}).click()
    const mask=await id('sectorGuide').boundingBox()
    await page.mouse.move(mask.x+mask.width*.2,mask.y+mask.height*.2)
    await page.mouse.down()
    await page.mouse.move(mask.x+mask.width*.75,mask.y+mask.height*.75,{steps:6})
    await page.mouse.up()
    assert.equal(await id('effectTarget').textContent(),'Rectángulo 1')
    assert.ok(await id('layerDesk').getByRole('button',{name:'Añadir efecto',exact:true}).isVisible())
    await id('addSectorEffect').click()
    await id('sectorLibrary').click()
    await mix.click()
    await pixel(.5,.5,[127,0,127])
    await pixel(.05,.05,[255,0,0])
    await tab('sectors')
    assert.match(await id('sectorControls').innerText(),/Eco azul[\s\S]*En salida/)
    const slider=id('sectorControls').locator('input[type=range]')
    await slider.focus()
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('ArrowRight')
    assert.equal(await slider.inputValue(),'0.53')
    assert.equal(await slider.evaluate(e=>e.style.getPropertyValue('--amount')),'53%')
    await pixel(.5,.5,[120,0,135])
    const layerSwitch=id('sectorControls').getByRole('button',{name:'Activación de Eco azul'})
    await layerSwitch.click()
    await pixel(.5,.5,[255,0,0])
    await layerSwitch.click()
    assert.equal(await slider.inputValue(),'0.53')
    await pixel(.5,.5,[120,0,135])
    await id('liveEdit').click()
    await layerSwitch.click()
    assert.equal(await layerSwitch.getAttribute('aria-pressed'),'false')
    assert.match(await id('sectorControls').innerText(),/Cambio pendiente/)
    await pixel(.5,.5,[120,0,135])
    await tab('library')
    await id('applySectors').click()
    await pixel(.5,.5,[255,0,0])
    await tab('sectors')
    assert.match(await id('sectorControls').innerText(),/Pausado/)
    await id('liveEdit').click()
    await layerSwitch.click()
    await pixel(.5,.5,[120,0,135])
    await page.evaluate(()=>{
      const start = MediaRecorder.prototype.start
      MediaRecorder.prototype.start = function (...args) {
        this.addEventListener('dataavailable',event=>{
          if (event.data.size>1) window.sectorLoopHasData=true
        })
        return start.apply(this,args)
      }
    })
    await id('loopButton').click()
    assert.equal(await id('loopButton').getAttribute('aria-pressed'),'true',await id('toast').textContent())
    await page.waitForFunction(()=>window.sectorLoopHasData,null,{timeout:10000})
    await id('loopButton').click()
    await page.waitForFunction(()=>/Loop guardado|elegí un archivo|no se pudo grabar/i.test(document.getElementById('toast').textContent))
    assert.match(await id('toast').textContent(),/Loop guardado/)
    await tab('library')
    await page.locator('[data-shelf=loops]').click()
    const reuse=id('loopList').getByRole('button',{name:/Usar Rectángulo/})
    await reuse.click()
    await page.waitForFunction(()=>document.getElementById('sectorFileButton').textContent.includes('Rectángulo'))
    await id('sector-tree-1').getByRole('button',{name:/Editar Eco azul en/}).click()
    await id('stackRemove').click()
    await page.waitForFunction(()=>{
      const {regl,canvas}=hydraSynth
      const [red,green,blue]=regl.read({x:canvas.width/2,y:canvas.height/2,width:1,height:1})
      return Math.abs(red-120)<18 && green<18 && Math.abs(blue-135)<18
    })
    await id('sector-tree-1').getByRole('button',{name:/^Loop · Rectángulo/}).click()
    await id('sectorClearInput').click()
    await id('sectorCodeToggle').click()
    await id('sectorCode').fill('solid(0,1,0).out()')
    await id('sectorApplyCode').click()
    await pixel(.5,.5,[0,255,0])
    await pixel(.05,.05,[255,0,0])
    await id('sectorCode').fill('')
    await id('sectorApplyCode').click()
    const quality=await page.evaluate(()=>{
      const source=document.createElement('canvas')
      source.width=32; source.height=24
      const c=source.getContext('2d')
      c.fillStyle='#ff0000'; c.fillRect(0,0,16,24)
      c.fillStyle='#0000ff'; c.fillRect(16,0,16,24)
      const paint=new BrushSurface()
      const first=paint.paint(source,1,.42,0,3,1)
      let end
      for (let t=46;t<2700;t+=45) end=paint.paint(source,t,.42,0,3,1)
      return [first!==source,end===source,paint.progress]
    })
    assert.deepEqual(quality,[true,true,1])
    const inverse=await page.evaluate(()=>{
      const source=document.createElement('canvas')
      source.width=32; source.height=24
      const c=source.getContext('2d')
      c.fillStyle='#fff'; c.fillRect(0,0,16,24)
      c.fillStyle='#000'; c.fillRect(16,0,16,24)
      const strokes=new BrushSurface()
      const first=strokes.paint(source,1,.42,0,3,0,true)
      let end
      for (let t=46;t<2700;t+=45) end=strokes.paint(source,t,.42,0,3,0,true)
      const normal=end.getContext('2d')
      return [first===source,strokes.progress,normal.getImageData(4,4,1,1).data[0],
        normal.getImageData(end.width-4,4,1,1).data[0]]
    })
    assert.deepEqual(inverse,[true,1,223,19])
    await page.context().grantPermissions(['camera'])
    if (!await id('sectorMedia').isVisible()) await id('sectorMediaToggle').click()
    await page.locator('[data-sector-src=s0]').click()
    await id('sectorCamera').click()
    await page.waitForFunction(()=>s0.src?.videoWidth)
    await page.evaluate(()=>window.trackToCheck=s0.src.srcObject.getVideoTracks()[0])
    await id('sectorDisconnect').click()
    await page.waitForFunction(()=>trackToCheck.readyState==='ended')
    assert.deepEqual(errors,[])
    console.log('PASS: anchored help, effect switches, isolated feedback and sector code, layer status, keyboard slider, decoded sector loop, brush in both directions and camera disconnect.')
  } finally { await browser.close() }
}
main().catch(e=>{console.error(e);process.exitCode=1})
