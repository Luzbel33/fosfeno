const assert=require('node:assert/strict')
const {readFile}=require('node:fs/promises')
const {chromium}=require('playwright')

async function main() {
  const url=new URL(process.argv[2] || 'http://127.0.0.1:8736/')
  url.searchParams.set('mode','mapeo')
  const browser=await chromium.launch({channel:'chromium',args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']})
  try {
    const p=await browser.newPage({viewport:{width:1400,height:840}})
    const errors=[]
    p.on('pageerror',e=>errors.push(e.message))
    await p.goto(url.href)
    const map=p.frameLocator('#mappingFrame'), id=name=>map.locator('#'+name)
    const click=name=>id(name).click(), handle=i=>map.locator('[data-corner="'+i+'"]')
    const drag=async(from,to)=>{
      const rect=await id('mapSurface').boundingBox()
      await p.mouse.move(rect.x+from[0]*rect.width,rect.y+from[1]*rect.height)
      await p.mouse.down()
      await p.mouse.move(rect.x+to[0]*rect.width,rect.y+to[1]*rect.height,{steps:12})
      await p.mouse.up()
    }
    const corners=()=>map.locator('#mapHandles button').evaluateAll(bs=>bs.map(b=>[parseFloat(b.style.left)/100,parseFloat(b.style.top)/100]))
    const transform=async(name,value)=>{
      if (!await id(name).isVisible()) await id('mapTransformFields').locator('summary').click()
      await id(name).fill(String(value))
      await id(name).press('Enter')
    }
    await id('mapMain').waitFor()
    const file={name:'Dos colores.svg',mimeType:'image/svg+xml',buffer:Buffer.from(
      '<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"><rect width="100" height="100" fill="red"/><rect x="50" width="50" height="100" fill="blue"/></svg>')}
    await id('mapMediaFile').setInputFiles(file)
    await map.locator('#mapSurface[data-cursor=place]').waitFor()
    await drag([.18,.20],[.78,.80])
    const [out]=await Promise.all([p.waitForEvent('popup'),click('mapOutput')])
    const pixel=(x,y,expected)=>out.waitForFunction(({x,y,expected})=>{
      const c=document.querySelector('canvas'), gl=c?.getContext('webgl')
      if (!gl) return false
      const rgba=new Uint8Array(4)
      gl.readPixels(Math.round((c.width-1)*x),Math.round((1-y)*(c.height-1)),1,1,gl.RGBA,gl.UNSIGNED_BYTE,rgba)
      return expected.every((n,i)=>Math.abs(n-rgba[i])<10)
    },{x,y,expected},{timeout:6500})
    await pixel(.23,.25,[255,0,0])
    await click('mapDeform')
    await handle(0).waitFor()
    const original=await corners()
    await drag(original[0],[.45,.37])
    const warped=await corners()
    assert.ok(warped[0][0]>.44 && warped[0][1]>.36)
    assert.deepEqual(warped.slice(1),original.slice(1))
    await pixel(.23,.25,[0,0,0])
    const {mapQuadPoint}=await import('../src/mapping-warp.mjs')
    const red=mapQuadPoint([.25,.6],warped), blue=mapQuadPoint([.75,.6],warped)
    await pixel(...red,[255,0,0]); await pixel(...blue,[0,0,255])
    await click('mapUndo')
    await pixel(.23,.25,[255,0,0])
    assert.deepEqual(await corners(),original)
    await click('mapRedo')
    await pixel(.23,.25,[0,0,0])
    await handle(1).focus()
    await p.keyboard.press('Shift+ArrowLeft')
    const adjusted=await corners()
    const cw=await id('mapPreview').evaluate(c=>c.width)
    assert.ok(Math.abs((warped[1][0]-adjusted[1][0])*cw-10)<.002)
    const green=await out.evaluate(()=>{
      const c=document.querySelector('canvas'), gl=c.getContext('webgl'), bytes=new Uint8Array(c.width*c.height*4)
      gl.readPixels(0,0,c.width,c.height,gl.RGBA,gl.UNSIGNED_BYTE,bytes)
      let count=0; for(let i=1;i<bytes.length;i+=4) if(bytes[i]>30) count++
      return count
    })
    assert.equal(green,0,'Los cuatro tiradores y la guía verde deben existir sólo en cabina.')
    await map.locator('[data-tool=select]').click()
    await drag(red,[red[0]+.05,red[1]+.03])
    await id('mapSurface').focus()
    await p.keyboard.press('ArrowRight')
    await click('mapDeform')
    const moved=await corners()
    for(let i=0;i<4;i++) {
      assert.ok(Math.abs((moved[i][0]-adjusted[i][0])-.05)<.005)
      assert.ok(Math.abs((moved[i][1]-adjusted[i][1])-.03)<.005)
    }
    await click('mapSave')
    await id('mapStatus').filter({hasText:/guardados/}).waitFor()
    const download=p.waitForEvent('download')
    await click('mapExport')
    const bytes=await readFile(await (await download).path())
    const {unpackMap}=await import('../src/mapping-project.mjs')
    const saved=await unpackMap(new Blob([bytes]))
    assert.ok(saved.layers[0].quad.every(([x,y],i)=>Math.abs(x-moved[i][0])+Math.abs(y-moved[i][1])<.00001))
    await p.reload()
    await click('mapRestore')
    await id('mapLayers').getByRole('button',{name:file.name,exact:true}).click()
    await click('mapDeform')
    assert.deepEqual(await corners(),moved)
    await id('mapTransformFields').locator('summary').click()
    await click('mapResetQuad')
    assert.notDeepEqual(await corners(),moved)
    await id('mapProjectFile').setInputFiles({name:'quad.fosmap',mimeType:'application/octet-stream',buffer:bytes})
    await id('mapStatus').filter({hasText:/Mapa importado/}).waitFor()
    await id('mapLayers').getByRole('button',{name:file.name,exact:true}).click()
    await click('mapDeform')
    assert.deepEqual(await corners(),moved)
    const [projector]=await Promise.all([p.waitForEvent('popup'),click('mapOutput')])
    const color=(x,y,expected)=>projector.waitForFunction(({x,y,expected})=>{
      const c=document.querySelector('canvas'), gl=c?.getContext('webgl')
      if (!gl) return false
      const p=new Uint8Array(4)
      gl.readPixels(Math.round((c.width-1)*x),Math.round((1-y)*(c.height-1)),1,1,gl.RGBA,gl.UNSIGNED_BYTE,p)
      return expected.every((v,i)=>Math.abs(v-p[i])<12)
    },{x,y,expected},{timeout:6500})
    await transform('mapX',140)
    await id('mapLayers').getByText(/Fuera del lienzo/).waitFor()
    assert.ok((await corners()).every(([x])=>x>1))
    await color(.55,.5,[0,0,0])
    const offDownload=p.waitForEvent('download')
    await click('mapExport')
    const offBytes=await readFile(await (await offDownload).path())
    const outside=(await unpackMap(new Blob([offBytes]))).layers[0]
    assert.ok(outside.quad.every(([x])=>x>1))
    await click('mapCenter')
    await transform('mapRotate',90)
    const rotated=await corners()
    assert.ok(Math.abs(rotated[0][0]-rotated[1][0])<.000001 && rotated[1][1]>rotated[0][1])
    await color(...mapQuadPoint([.25,.55],rotated),[255,0,0])
    await color(...mapQuadPoint([.75,.55],rotated),[0,0,255])
    await transform('mapScale',65)
    const ratio=Number(await id('mapWidth').inputValue())/Number(await id('mapHeight').inputValue())
    await transform('mapScale',80)
    assert.ok(Math.abs(Number(await id('mapWidth').inputValue())/Number(await id('mapHeight').inputValue())-ratio)<.001)
    const height=Number(await id('mapHeight').inputValue())
    await transform('mapWidth',35)
    assert.ok(Math.abs(Number(await id('mapHeight').inputValue())-height)<.001)
    await transform('mapX',0)
    assert.ok((await corners()).some(([x])=>x<0))
    await color(.97,.5,[0,0,0])
    await id('mapProjectFile').setInputFiles({name:'fuera.fosmap',mimeType:'application/octet-stream',buffer:offBytes})
    await id('mapStatus').filter({hasText:/Mapa importado/}).waitFor()
    await id('mapLayers').getByText(/Fuera del lienzo/).click()
    await click('mapCenter')
    await click('mapDeform')
    const centered=await corners()
    await color(...mapQuadPoint([.25,.55],centered),[255,0,0])
    await map.locator('[data-tool=select]').click()
    const start=mapQuadPoint([.05,.92],centered)
    const end=[start[0]+1.02-Math.min(...centered.map(p=>p[0])),start[1]]
    await drag(start,end)
    await id('mapLayers').getByText(/Fuera del lienzo/).waitFor()
    await color(.5,.55,[0,0,0])
    await click('mapUndo')
    await color(...mapQuadPoint([.25,.55],centered),[255,0,0])

    const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
    try {
      const phone=await mobile.newPage(), touch=await mobile.newCDPSession(phone)
      phone.on('pageerror',e=>errors.push(e.message))
      await phone.goto(url.href)
      const fm=phone.frameLocator('#mappingFrame'), selector=name=>fm.locator('#'+name)
      await selector('mapProjectFile').setInputFiles({name:'movil.fosmap',mimeType:'application/octet-stream',buffer:bytes})
      await selector('mapStatus').filter({hasText:/Mapa importado/}).waitFor()
      await selector('mapLayers').getByRole('button',{name:file.name,exact:true}).tap()
      await selector('mapDeform').tap()
      const grip=selector('mapHandles').locator('[data-corner="0"]')
      const before=await grip.getAttribute('style'), box=await grip.boundingBox()
      const at={x:box.x+box.width/2,y:box.y+box.height/2}
      await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[at]})
      for (let i=1;i<=5;i++)
        await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:at.x+4*i,y:at.y+2*i}]})
      await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
      await grip.evaluate((b,style)=>new Promise((resolve,reject)=>{
        const end=performance.now()+4000
        const check=()=>b.getAttribute('style')!==style ? resolve() : performance.now()>end ? reject(Error('La esquina táctil no se movió')) : requestAnimationFrame(check)
        check()
      }),before)
      assert.equal(await selector('mapMain').evaluate(el=>el.ownerDocument.documentElement.scrollWidth<=el.ownerDocument.defaultView.innerWidth),true)
    } finally { await mobile.close() }
    assert.deepEqual(errors,[])
    console.log('Perspectiva, arrastre, giro, escala uniforme e independiente, ajuste fino, salida sin guías, objetos fuera del lienzo y recuperación local y por archivo.')
  } finally { await browser.close() }
}
main().catch(e=>{console.error(e);process.exitCode=1})
