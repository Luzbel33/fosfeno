// Chromium's headless virtual screens exercise the real Window Management API.
const assert = require('node:assert/strict')
const { chromium } = require('playwright')

const studio = new URL(process.argv[2] || 'http://127.0.0.1:8736/')
const projector = 'Proyector virtual de ensayo'
const bounds = page => page.evaluate(()=>[screenX,screenY,outerWidth,outerHeight])
async function choose(page) {
  await page.locator('#chooseOutput').click()
  await page.locator('#chooseDisplay').click()
}
async function project(page,button) {
  const [popup] = await Promise.all([page.waitForEvent('popup'),button.click()])
  return popup
}
async function assertPublic(page,tag) {
  await page.locator(tag).first().waitFor()
  assert.equal(await page.locator('button, dialog, input, #toast').count(),0)
}
async function check() {
  const browser = await chromium.launch({channel:'chromium',args:['--use-angle=d3d11','--enable-unsafe-swiftshader']})
  try {
    const context = await browser.newContext({viewport:null,serviceWorkers:'block'})
    const page = await context.newPage()
    const devtools = await context.newCDPSession(page)
    const {targetInfo} = await devtools.send('Target.getTargetInfo')
    const permission = setting=>devtools.send('Browser.setPermission',{
      permission:{name:'window-management'},setting,origin:studio.origin,browserContextId:targetInfo.browserContextId})
    const first = await devtools.send('Emulation.addScreen',{left:1100,top:0,width:900,height:700,label:projector})
    await page.addInitScript(()=>{
      const get = window.getScreenDetails.bind(window)
      window.discoveryCalls=0
      window.getScreenDetails=()=>{discoveryCalls++;return get()}
    })
    await page.goto(studio.href)
    await page.waitForFunction(()=>window.hydraSynth && window.fosfenoDisplay)
    const booth = await bounds(page)
    const run = page.locator('#project')
    let output = await project(page,run)
    await assertPublic(output,'video')
    assert.equal(await page.evaluate(()=>discoveryCalls),1,'El primer Proyectar inicia la detección de pantallas')
    await output.close()
    await permission('denied')
    await choose(page)
    await page.waitForFunction(()=>document.querySelector('#displayStatus').textContent.includes('Extender'))
    await page.locator('#cancelDisplay').click()
    assert.equal(await page.evaluate(()=>localStorage.getItem('fosfeno:projectorDisplay')),null)
    output=await project(page,run)
    const original = await bounds(output)
    assert.ok(original[0]<1100)
    // Simulate a browser that ignores a placement request without throwing.
    await output.evaluate(()=>{window.actualMove=window.moveTo;window.moveTo=()=>{}})
    await permission('granted')
    await choose(page)
    await page.locator('#displayChoices button').filter({hasText:projector}).click()
    await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('Separá la pestaña'))
    assert.deepEqual(await bounds(page),booth)
    assert.deepEqual(await bounds(output),original)
    // Same native-window geometry can mean the audience view is another tab.
    await output.evaluate(booth=>{
      window.displayKeys=['screenX','screenY','outerWidth','outerHeight']
      window.savedDescriptors=displayKeys.map(key=>Object.getOwnPropertyDescriptor(window,key))
      displayKeys.forEach((key,i)=>Object.defineProperty(window,key,{configurable:true,value:booth[i]}))
      window.moveAttempts=0
      window.moveTo=()=>{moveAttempts++}
    },booth)
    await run.click()
    await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('Separá la pestaña'))
    assert.equal(await output.evaluate(()=>moveAttempts),0)
    await output.evaluate(()=>{
      displayKeys.forEach((key,i)=>savedDescriptors[i] ? Object.defineProperty(window,key,savedDescriptors[i]) : delete window[key])
      window.moveTo=window.actualMove
    })
    await run.click()
    await output.waitForFunction(()=>screenX>=1100)
    await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('Salida ubicada en'))
    await output.close()
    output=await project(page,run)
    await assertPublic(output,'video')
    await output.waitForFunction(()=>screenX>=1100)
    assert.deepEqual(await bounds(page),booth)
    // Returning to an open output must not create another public window.
    await output.evaluate(()=>{
      window.fullscreenEvents=[]
      for (const name of ['dblclick','fullscreenchange','fullscreenerror']) document.addEventListener(name,event=>{
        fullscreenEvents.push([name,!!document.fullscreenElement,navigator.userActivation.isActive,event.target.nodeName])
      })
    })
    await run.click()
    assert.equal(context.pages().length,2)
    if (!await output.evaluate(()=>!!document.fullscreenElement)) await output.locator('video').dblclick()
    await output.waitForFunction(()=>!!document.fullscreenElement,null,{timeout:6000}).catch(async cause=>{
      const state=await output.evaluate(()=>[screenX,screenY,outerWidth,outerHeight,fullscreenEvents])
      throw new Error('Pantalla completa: '+JSON.stringify(state)+' · '+(await page.locator('#toast').textContent()),{cause})
    })
    await choose(page)
    await page.locator('#cancelDisplay').click()
    assert.ok(await output.evaluate(()=>!!document.fullscreenElement))
    await output.locator('video').dblclick()
    await output.waitForFunction(()=>!document.fullscreenElement)
    await choose(page)
    await page.locator('#manualDisplay').click()
    const calls = await page.evaluate(()=>discoveryCalls)
    await run.click()
    assert.equal(await page.evaluate(()=>discoveryCalls),calls)
    await page.locator('#chooseOutput').click()
    await page.locator('#showProjectorCode').click()
    await output.locator('#projectedCode').waitFor()
    await output.evaluate(()=>{
      window.firstVideo=document.querySelector('video')
      window.firstTrack=firstVideo.srcObject.getVideoTracks()[0]
      window.firstOverlay=document.querySelector('#projectedCode')
    })
    if (await page.locator('#outputChoices').isVisible()) await page.locator('#chooseOutput').click()
    await choose(page)
    await page.locator('#displayChoices button').filter({hasText:projector}).click()
    await page.locator('#openMapping').click()
    const map = page.frameLocator('#mappingFrame')
    await map.locator('#mapOutput').waitFor()
    assert.equal(await output.locator('video').count(),1,'Abrir la mesa conserva la salida del Estudio')
    await map.locator('#mapOutput').click()
    assert.equal(context.pages().length,2,'Mapeo toma la ventana que ya tiene Estudio')
    await assertPublic(output,'canvas')
    assert.deepEqual(await output.evaluate(()=>[firstTrack.readyState,firstVideo.ondblclick,firstOverlay.isConnected,document.querySelectorAll('#projectedCode').length]),['ended',null,false,1])
    await output.waitForFunction(()=>screenX>=1100)
    assert.deepEqual(await bounds(page),booth)
    await output.evaluate(()=>{
      window.firstCanvas=document.querySelector('canvas')
      window.firstGL=firstCanvas.getContext('webgl')
      window.mapOverlay=document.querySelector('#projectedCode')
    })
    await page.locator('#exitMapping').click()
    await assertPublic(output,'video')
    assert.equal(await output.locator('canvas').count(),0)
    assert.deepEqual(await output.evaluate(()=>[firstGL.isContextLost(),document.querySelector('video').srcObject.getVideoTracks()[0].readyState]),[true,'live'])
    assert.deepEqual(await output.evaluate(()=>[firstCanvas.ondblclick,mapOverlay.isConnected,document.querySelectorAll('#projectedCode').length]),[null,false,1])
    assert.equal(context.pages().length,2)
    await page.locator('#openMapping').click()
    await map.locator('#mapOutput').click()
    await assertPublic(output,'canvas')
    await output.goto(new URL('assets/mark.svg',studio).href)
    const old = output
    const originalBounds = await bounds(old)
    output = await project(page,map.locator('#mapOutput'))
    await assertPublic(output,'canvas')
    assert.deepEqual(await bounds(old),originalBounds)
    await old.close()
    await devtools.send('Emulation.removeScreen',{screenId:first.screenInfo.id})
    await map.locator('#mapStatus').filter({hasText:/Extender/}).waitFor()
    const again=await devtools.send('Emulation.addScreen',{left:1100,top:0,width:900,height:700,label:projector})
    await output.waitForFunction(()=>screenX>=1100)
    await output.close()
    await devtools.send('Emulation.removeScreen',{screenId:again.screenInfo.id})
    await page.goto(studio.href)
    await page.waitForFunction(()=>window.hydraSynth)
    output = await project(page,run)
    await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('Extender'))
    assert.deepEqual(await bounds(page),booth)
    await output.close()
    await page.evaluate(()=>{window.getScreenDetails=undefined})
    await choose(page)
    await page.waitForFunction(()=>document.querySelector('#displayStatus').textContent.includes('ubicar la salida a mano'))
    await page.locator('#cancelDisplay').click()
    await page.evaluate(()=>{window.open=()=>null})
    await run.click()
    await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('ventanas emergentes'))
    assert.equal(context.pages().length,1)
    await page.evaluate(()=>localStorage.removeItem('fosfeno:projectorDisplay'))
    await page.reload()
    await page.waitForFunction(()=>window.hydraSynth)
    await devtools.send('Emulation.addScreen',{left:1100,top:0,width:900,height:700,label:projector})
    await devtools.send('Browser.setPermission',{permission:{name:'fullscreen',allowWithoutGesture:true},setting:'granted',
      origin:studio.origin,browserContextId:targetInfo.browserContextId})
    output=await project(page,run)
    await output.waitForFunction(()=>screenX>=1100 && !!document.fullscreenElement)
    assert.equal(await page.locator('#displayDialog').isVisible(),false)
    assert.deepEqual(await bounds(page),booth)
    await devtools.send('Emulation.addScreen',{left:2100,top:0,width:800,height:600,label:'Pantalla auxiliar'})
    await choose(page)
    await page.locator('#displayChoices button').filter({hasText:'Pantalla auxiliar'}).click()
    await page.waitForFunction(()=>{
      const output=fosfenoDisplay.current()
      return output.screenX>=2100 || document.querySelector('#toast').textContent.includes('monitor anterior')
    })
    assert.ok(await output.evaluate(()=>!!document.fullscreenElement))
    assert.deepEqual(await bounds(page),booth)
    await output.close()
    await page.evaluate(()=>localStorage.removeItem('fosfeno:projectorDisplay'))
    await page.reload()
    await page.waitForFunction(()=>window.hydraSynth)
    output=await project(page,run)
    await page.locator('#displayChoices button').filter({hasText:'Pantalla auxiliar'}).waitFor()
    await page.locator('#cancelDisplay').click()
    assert.equal(await page.evaluate(()=>localStorage.getItem('fosfeno:projectorDisplay')),null)
    await output.close()
    console.log('Chromium, pantallas virtuales: primer acceso, único monitor externo y fullscreen permitido con un clic; selección de varias pantallas, cancelación, reconexión, ubicación manual y cabina inmóvil. Transferencia Estudio → Mapeo → Estudio en una ventana con liberación de la pista y del contexto WebGL.')
  } finally { await browser.close() }
}
check().catch(error=>{console.error(error);process.exitCode=1})
