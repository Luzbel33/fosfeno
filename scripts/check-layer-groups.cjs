const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const { readFile } = require('node:fs/promises')

;(async () => {
  const url = process.argv[2] || 'http://127.0.0.1:8736/'
  const browser = await chromium.launch({channel:'chromium',args:['--use-angle=d3d11','--enable-unsafe-swiftshader']})
  try {
    const page = await browser.newPage({viewport:{width:1480,height:900}})
    await page.addInitScript(() => {
      const nativePlay = HTMLMediaElement.prototype.play
      HTMLMediaElement.prototype.play = function (...args) {
        if (this instanceof HTMLVideoElement && this.loop) window.qaLoopVideo = this
        return nativePlay.apply(this,args)
      }
    })
    page.setDefaultTimeout(6000)
    const errors = []
    page.on('pageerror', error => { errors.push(error.message); console.log('page error:',error.stack) })
    page.on('console', message => { if (message.type()==='error') console.log('browser console:',message.text()) })
    const id = name => page.locator('#'+name)
    const click = name => id(name).click()
    const sample = (rgb,x=.4,y=.4) => page.waitForFunction(({rgb,x,y}) => {
      const c=hydraSynth.canvas,r=hydraSynth.regl
      const p=r.read({x:Math.floor(x*c.width),y:Math.floor((1-y)*c.height),width:1,height:1})
      return rgb.every((v,i)=> Math.abs(p[i]-v)<6)
    },{rgb,x,y},{timeout:5000})
    const edit = async text => {
      await click('sectorCodeToggle')
      await id('sectorCode').fill(text)
      await click('sectorApplyCode')
    }
    await page.goto(url)
    await page.waitForFunction(()=>window.cm?.getValue().startsWith('// Semilla') && window.hydraSynth)
    await page.evaluate(()=>cm.setValue('setResolution(320,180)\nsolid(0,0,0).out(o0)'))
    await sample([0,0,0])
    await click('newSector')
    await id('sectorShapes').getByRole('button',{name:'Rectángulo',exact:true}).click()
    const r = await id('sectorGuide').boundingBox()
    await page.mouse.move(r.x+.22*r.width,r.y+.22*r.height)
    await page.mouse.down()
    await page.mouse.move(r.x+.7*r.width,r.y+.75*r.height,{steps:5})
    await page.mouse.up()
    await edit('return solid(1,0,0,0.5)')
    await sample([128,0,0])
    await click('addSectorLayer')
    await edit('return solid(0,1,0,0.5)')
    await sample([64,128,0])
    await click('groupSectorLayers')
    await page.getByRole('button',{name:'Marcar Base',exact:true}).click()
    await page.getByRole('button',{name:'Marcar Capa 2',exact:true}).click()
    await click('createSectorGroup')
    await sample([64,128,0])
    const tree = id('sector-tree-1')
    assert.equal(await tree.locator('.layer-tree-children > .layer-tree-item').count(),2)
    await click('addSectorEffect')
    await id('sectorFx').getByRole('button',{name:'Invertir',exact:true}).click()
    await sample([128,64,191])
    await sample([0,0,0],.1,.1)
    await tree.getByRole('button',{name:/Pausar Invertir/}).click()
    await sample([64,128,0])
    await tree.getByRole('button',{name:/Activar Invertir/}).click()
    await sample([128,64,191])
    await tree.getByRole('button',{name:/Grupo/}).first().focus()
    await page.keyboard.press('Control+z')
    await sample([64,128,0])
    await page.keyboard.press('Control+Shift+z')
    await sample([128,64,191])
    await tree.getByRole('button',{name:'Grupo 3',exact:true}).click()
    await page.keyboard.press('Control+c')
    await page.keyboard.press('Control+v')
    await page.waitForFunction(()=>document.querySelectorAll('#sector-tree-1 .layer-tree-children').length===2)
    await page.keyboard.press('Control+z')
    await page.waitForFunction(()=>document.querySelectorAll('#sector-tree-1 .layer-tree-children').length===1)
    await page.keyboard.press('Control+y')
    await page.waitForFunction(()=>document.querySelectorAll('#sector-tree-1 .layer-tree-children').length===2)
    await page.keyboard.press('Control+z')
    await page.waitForFunction(()=>document.querySelectorAll('#sector-tree-1 .layer-tree-children').length===1)
    await tree.getByRole('button',{name:'Grupo 3',exact:true}).click()
    await click('removeSectorLayer')
    await sample([64,128,0])
    await page.keyboard.press('Control+z')
    await sample([128,64,191])
    await tree.getByRole('button',{name:'Grupo 3',exact:true}).click()
    await click('openLoops')
    await id('loopFile').setInputFiles('media/fosfeno-demo.mp4')
    await id('loopList').getByRole('button',{name:'Usar fosfeno-demo.mp4',exact:true}).click()
    const loop = tree.locator('.layer-tree-children').getByRole('button',{name:'Loop · fosfeno-demo.mp4',exact:true})
    await loop.waitFor()
    assert.match(await id('toast').textContent(),/Loop cargado en Rectángulo 1 · Capa/)
    await page.waitForFunction(()=>window.qaLoopVideo?.currentTime>.1 && window.qaLoopVideo.videoWidth>100)
    await loop.click()
    assert.equal(await id('sectorFileButton').textContent(),'fosfeno-demo.mp4')
    await id('sectorStorage').locator('summary').click()
    await click('saveSectors')
    await page.waitForFunction(()=>document.getElementById('sectorStatus').textContent.includes('guardados'))
    await loop.locator('xpath=ancestor::*[contains(@class,"layer-tree-item")][1]').locator(':scope > .layer-tree-head .layer-tree-name').click()
    await click('removeSectorLayer')
    await loop.waitFor({state:'hidden'})
    await click('loadSectors')
    await loop.waitFor()
    console.log('Loop playback, hierarchy and local save/reload passed')

    assert.ok(await id('libraryPage').isVisible(),'selecting layers keeps the library open')
    await page.locator('#studioNav [data-view="code"]').click()
    await page.getByRole('textbox',{name:'Nombre del sketch'}).fill('QA grupo y loop')
    await page.locator('button[data-view="library"]').click()
    await page.locator('[data-shelf=projects]').click()
    await click('projectSave')
    const row=id('projectList').locator('details').filter({hasText:'QA grupo y loop'})
    await row.locator('summary').click()
    const [download] = await Promise.all([
      page.waitForEvent('download'), row.getByRole('button',{name:'Descargar',exact:true}).click()
    ])
    const packageData=await readFile(await download.path())
    assert.ok(packageData.length>8_000_000)
    const mobile=await browser.newContext({viewport:{width:375,height:812},hasTouch:true,isMobile:true,deviceScaleFactor:1})
    const mp=await mobile.newPage()
    mp.setDefaultTimeout(7500)
    mp.on('pageerror',error=>{errors.push(error.message);console.log('mobile page error:',error.stack)})
    await mp.goto(url)
    await mp.waitForFunction(()=>window.cm?.getValue().trim() && window.hydraSynth)
    await mp.locator('button[data-view="library"]').tap()
    await mp.locator('[data-shelf=projects]').tap()
    await mp.locator('#projectFile').setInputFiles({name:download.suggestedFilename(),mimeType:'application/octet-stream',buffer:packageData})
    const imported=mp.locator('#projectList details').filter({hasText:'QA grupo y loop'})
    await imported.locator('summary').tap()
    await imported.getByRole('button',{name:'Activar',exact:true}).tap()
    await mp.waitForFunction(()=>document.querySelector('#toast').textContent.includes('Composición en salida · QA grupo y loop'))
    await mp.locator('#backToLayers').tap()
    const mobileTree=mp.locator('#sector-tree-1')
    await mobileTree.locator('.layer-tree-children').getByRole('button',{name:'Loop · fosfeno-demo.mp4',exact:true}).waitFor()
    assert.equal(await mp.evaluate(()=>{
      const tree=document.querySelector('#sector-tree-1')
      return document.documentElement.scrollWidth===innerWidth && tree.scrollWidth<=tree.clientWidth
    }),true)
    if (process.env.MAP_SHOTS) await mp.screenshot({path:process.env.MAP_SHOTS+'/fosfeno-loops-grupos-movil.png'})
    await mobile.close()
    assert.deepEqual(errors,[])
    console.log('Browser/group QA passed: compositing, effect toggle, copy/paste, undo/redo, ungroup, loop import/playback in the hierarchy, local save/reload and portable import on 375px touch.')
  } finally { await browser.close() }
})().catch(error=>{console.error(error);process.exitCode=1})
