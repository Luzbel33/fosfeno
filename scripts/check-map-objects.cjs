const assert = require('node:assert/strict')
const {readFile} = require('node:fs/promises')
const path = require('node:path')
const {chromium} = require('playwright')

const url = new URL(process.argv[2] || 'http://127.0.0.1:8736/')
url.searchParams.set('mode','mapeo')
const photo = (name,color) => ({name,mimeType:'image/svg+xml',buffer:Buffer.from(
  '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24"><rect width="24" height="24" fill="'+color+'"/></svg>'
)})

async function main() {
  const browser = await chromium.launch({channel:'chromium',args:['--use-angle=d3d11','--enable-unsafe-swiftshader']})
  try {
    const p = await browser.newPage({viewport:{width:1440,height:900}})
    p.setDefaultTimeout(6500)
    const errors=[]
    p.on('pageerror',e=>errors.push(e.message))
    await p.goto(url.href)
    const desk=p.frameLocator('#mappingFrame'), id=name=>desk.locator('#'+name)
    const click=name=>id(name).click()
    await id('mapMain').waitFor()
    const drag=async(start,end)=>{
      const box=await id('mapPreview').boundingBox()
      await p.mouse.move(box.x+start[0]*box.width,box.y+start[1]*box.height)
      await p.mouse.down()
      await p.mouse.move(box.x+end[0]*box.width,box.y+end[1]*box.height,{steps:9})
      await p.mouse.up()
    }
    const point=async(x,y,expected)=>{
      const frame=p.frames().find(f=>f.url().includes('mapeo.html'))
      await frame.waitForFunction(({x,y,expected})=>{
        const c=document.getElementById('mapPreview'), rgba=c.getContext('2d').getImageData(c.width*x,c.height*y,1,1).data
        return expected.every((v,i)=>Math.abs(rgba[i]-v)<8)
      },{x,y,expected})
    }
    const row=name=>id('mapLayers').getByRole('button',{name,exact:true})
    await desk.locator('[data-tool=brush]').click()
    await desk.locator('[data-brush=solid]').click()
    await drag([.2,.30],[.6,.30])
    await drag([.2,.45],[.6,.45])
    await point(.4,.45,[169,255,80,255])
    await row('Trazos 1').click()
    await id('mapStrokes').locator('summary').click()
    await id('mapStrokeList').getByRole('button',{name:'Trazo 2'}).click()
    await desk.locator('[data-color="#ff55ad"]').click()
    await point(.4,.45,[255,85,173,255])
    await point(.4,.30,[169,255,80,255])
    await click('mapRemoveStroke')
    await point(.4,.45,[0,0,0,0])
    await click('mapUndo')
    await point(.4,.45,[255,85,173,255])
    await drag([.4,.30],[.55,.40])
    await point(.52,.55,[255,85,173,255])
    await id('mapMediaFile').setInputFiles(photo('roja.svg','red'))
    await desk.locator('#mapSurface[data-cursor="place"]').waitFor()
    await drag([.28,.24],[.72,.68])
    await point(.52,.55,[255,0,0,255])
    await desk.locator('[data-mask=ellipse]').click()
    await id('mapOpacity').press('End')
    await id('mapOpacity').press('PageDown')
    await id('mapOpacity').press('PageDown')
    const opacity=Number(await id('mapOpacity').inputValue())
    assert.ok(opacity<100 && opacity>20)
    const alpha=Math.round(opacity*255/100)
    await point(.52,.49,[255,0,0,alpha])
    await id('mapLayerName').fill('Pantalla central')
    await id('mapLayerName').press('Enter')
    await row('Pantalla central').waitFor()
    const chooser=p.waitForEvent('filechooser')
    await click('mapReplace')
    await (await chooser).setFiles(photo('azul.svg','blue'))
    await point(.52,.49,[0,0,255,alpha])
    assert.equal(await desk.locator('[data-mask=ellipse]').getAttribute('aria-pressed'),'true')
    assert.equal(await id('mapOpacity').evaluate(e=>e.style.getPropertyValue('--amount')),opacity+'%')
    await id('mapOpacity').press('End')
    await desk.locator('[data-mask=rect]').click()
    await row('Pantalla central').waitFor()
    await click('mapLayerDown')
    await point(.52,.55,[255,85,173,255])
    await drag([.4,.34],[.48,.36])
    await click('mapLayerUp')
    await point(.52,.55,[0,0,255,255])
    const download=p.waitForEvent('download')
    await click('mapExport')
    const file=await download, bytes=await readFile(await file.path())
    const {unpackMap}=await import('../src/mapping-project.mjs')
    const map=await unpackMap(new Blob([bytes]))
    assert.deepEqual(map.layers.map(l=>l.name),['Trazos 1','Pantalla central'])
    assert.equal(map.layers[0].strokes.length,2)
    assert.equal(map.layers[0].strokes[1].color,'#ff55ad')
    assert.equal(map.layers[1].file.name,'azul.svg')
    await click('mapRemoveLayer')
    await point(.52,.55,[255,85,173,255])
    await id('mapProjectFile').setInputFiles({name:'ensayo.fosmap',mimeType:'application/octet-stream',buffer:bytes})
    await row('Pantalla central').click()
    await point(.52,.55,[0,0,255,255])
    await p.locator('#mappingSectors').click()
    await p.locator('#openLoops').click()
    await p.locator('#loopFile').setInputFiles(path.join(__dirname,'../media/fosfeno-demo.mp4'))
    await p.locator('#loopList').getByRole('button',{name:'Usar fosfeno-demo.mp4'}).waitFor()
    await p.locator('#mappingSurface').click()
    await click('mapReplaceLoop')
    await id('mapLoopList').getByRole('button',{name:'fosfeno-demo.mp4'}).click()
    await desk.locator('.map-layer-name').getByText('Loop · fosfeno-demo.mp4',{exact:true}).waitFor()
    await click('mapUndo')
    await point(.52,.55,[0,0,255,255])
    await row('Trazos 1').click()
    await click('mapToSector')
    await click('mapConfirmCopy')
    await p.waitForFunction(()=>fosfenoStack.snapshot().rows.some(r=>r.id && !r.visible && r.entries.some(l=>l.name==='Trazos 1' && l.source?.includes('.png'))))
    await p.locator('#mappingSurface').click()
    await row('Trazos 1').waitFor()
    assert.equal(await id('mapLayers').getByRole('button',{name:'Ocultar Trazos 1'}).isVisible(),true)
    await click('mapSave')
    await id('mapStatus').filter({hasText:/guardados en este navegador/}).waitFor()
    await p.locator('#exitMapping').click()
    await p.locator('#openMapping').click()
    await row('Pantalla central').waitFor()
    await p.reload()
    await id('mapMain').waitFor()
    assert.equal(await id('mapLayers').locator('.map-layer').count(),0)
    assert.equal(await desk.locator('[data-tool=brush]').getAttribute('aria-pressed'),'true')
    assert.equal(await desk.locator('[data-hydra=off]').getAttribute('aria-pressed'),'true')
    await click('mapRestore')
    await row('Pantalla central').waitFor()
    await point(.52,.55,[0,0,255,255])
    assert.deepEqual(errors,[])
    console.log('Mapeo: dos trazos editables y movibles, deshacer, reemplazar foto/loop, copia oculta a sector conservando trazos, orden por píxeles y .fosmap recuperado.')
  } finally { await browser.close() }
}
main().catch(e=>{console.error(e);process.exitCode=1})
